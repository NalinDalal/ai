# function is something that takes in some argument as input an returns something as output
def say_hi(name):
    """

    :param name: 

    """
    print("Hello " + name)

say_hi("Mike")
say_hi("Steve")

#return is used to return a value
def cube(num):
    """

    :param num: 

    """
    return num ** 3

print(cube(3))